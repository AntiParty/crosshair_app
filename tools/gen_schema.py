"""Regenerate core/src/schema_data.rs from the game's option repository.

    python tools/gen_schema.py <DA_OptionRepository.json>

Export the JSON with:
    Dump the asset Discovery/Content/Discovery/UI/Configuration/DA_OptionRepository to JSON with any Unreal
    asset tool (e.g. FModel's JSON export).
Run again after a game update to pick up new options or changed ranges.
"""
import json
import sys

src = sys.argv[1]
data = json.load(open(src, encoding="utf-8"))
floats, bools = [], []
for o in data:
    p = o.get("Properties") or {}
    tag = (p.get("OptionTag") or {}).get("TagName", "")
    if not ("Crosshair" in tag or tag.startswith("GameplayOption.Sights")):
        continue
    t = o.get("Type")
    if t == "EmbarkOptionFloat":
        lo = float(p.get("MinValue", 0.0))
        hi = float(p.get("MaxValue", 100.0 if "Opacity" in tag else 1.0))
        floats.append((tag, float(p.get("DefaultValue", 0.0)), lo, hi))
    elif t in ("EmbarkOptionBool", "GatedOptionBool"):
        bools.append((tag, bool(p.get("bDefaultValue", False))))
floats.sort()
bools.sort()

out = ["// Generated by tools/gen_schema.py from the game's DA_OptionRepository. Do not edit by hand.",
       "pub const FLOATS: &[(&str, f32, f32, f32)] = &["]
for k, d, lo, hi in floats:
    out.append(f'    ("{k}", {d!r}, {lo!r}, {hi!r}),')
out.append("];")
out.append("pub const BOOLS: &[(&str, bool)] = &[")
for k, d in bools:
    out.append(f'    ("{k}", {"true" if d else "false"}),')
out.append("];")
open("core/src/schema_data.rs", "w", encoding="utf-8").write("\n".join(out) + "\n")
print(len(floats), "floats,", len(bools), "bools")
